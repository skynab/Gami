import { chromium, devices } from '@playwright/test';
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await p.goto('http://localhost:5181/');
await p.waitForTimeout(1500);
const card = p.locator('a.card').nth(3);
await card.hover(); await p.waitForTimeout(500);
console.log('preview playing on hover (on):', await p.locator('.card-preview.playing').count());
await p.mouse.move(5, 500); await p.waitForTimeout(300);
await p.locator('button.brand').click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/menu.png`, clip: { x: 0, y: 0, width: 500, height: 200 } });
const item = p.getByRole('menuitemcheckbox');
console.log('checked before:', await item.getAttribute('aria-checked'));
await item.click();
console.log('checked after:', await item.getAttribute('aria-checked'));
await p.keyboard.press('Escape');
console.log('menu open after Escape:', await p.getByRole('menu').count());
await card.hover(); await p.waitForTimeout(500);
console.log('preview playing on hover (off):', await p.locator('.card-preview.playing').count());
await p.reload(); await p.waitForTimeout(1200);
await p.locator('a.card').nth(3).hover(); await p.waitForTimeout(500);
console.log('after reload still off:', await p.locator('.card-preview.playing').count(), JSON.stringify(await p.evaluate(() => localStorage.getItem('gami.settings'))));
await p.evaluate(() => localStorage.removeItem('gami.settings'));
// elsewhere the brand is a link home
await p.goto('http://localhost:5181/learn/crane'); await p.waitForTimeout(800);
console.log('brand on learn page is link:', await p.locator('a.brand').count(), 'button:', await p.locator('button.brand').count());
// phone: hold before playing
const m = await b.newPage({ ...devices['Pixel 7'] });
await m.goto('http://localhost:5181/');
await m.waitForTimeout(800);
await m.evaluate(() => window.scrollTo(0, 1200));
const t0 = Date.now();
let first = null;
for (let i = 0; i < 40; i++) { if (await m.locator('.card-preview.playing').count()) { first = Date.now() - t0; break; } await m.waitForTimeout(100); }
console.log('phone: preview started after ms:', first);
console.log('errors:', errors.join(' | ') || 'none');
await b.close();
